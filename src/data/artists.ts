// ─── DIALOGUE GENERATION (kept for backward compat) ──────────────────────

export const getArtistDialogue = (
  artist: NPCArtist,
  singerName: string,
  songTitle: string,
  isRemix: boolean = false
): string => {
  const origin = artist.origin || 'España';
  const greetings: Record<string, string> = {
    Argentina: `¡Che ${singerName}!`,
    Colombia: `¡Quiubo ${singerName}, parcero!`,
    'Puerto Rico': `Dímelo ${singerName}.`,
    México: `¡Qué onda ${singerName}!`,
    España: `Illo ${singerName},`,
  };
  const g = greetings[origin] || `Hey ${singerName},`;

  if (isRemix) {
    const remixLines: Record<string, string> = {
      Argentina: `${g} vengo escuchando en repeat tu tema "${songTitle}". Tengo unas barras durísimas para el Remix. ¿Lo sacamos?`,
      Colombia: `${g} ese tema "${songTitle}" está sonando en toda la calle. Quiero montarme en el Remix.`,
      'Puerto Rico': `${g} "${songTitle}" tiene to los códigos. Me tripea montarme en el Remix oficial.`,
      México: `${g} ese tema "${songTitle}" está muy pegado. Me late armar un remix, avísame.`,
      España: `${g} he escuchao "${songTitle}" y es un temazo. Le tiraría unas barras para el Remix Oficial.`,
    };
    return remixLines[origin] || `${g} me gusta "${songTitle}". ¿Hacemos el remix?`;
  }

  const lines: Record<string, string> = {
    Argentina: `${g} vengo siguiendo tus palos y la estás rompiendo mal wacho. ¿Armamos el junte?`,
    Colombia: `${g} tienes una vibra muy chimba. Montemos este junte ya.`,
    'Puerto Rico': `${g} estás sonando durísimo. Vamos a soltarlo.`,
    México: `${g} traes un estilazo bien bélico. Hay que aventarnos un junte.`,
    España: `${g} he visto cómo estás subiendo. Tengo una idea en mente. ¿Le damos?`,
  };
  return lines[origin] || `${g} ¿hacemos algo juntos?`;
};
